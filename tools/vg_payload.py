"""Payload of the native setup (native_d2/setup): everything the setup installs, packed for the C code.

  native_d2/setup/gen/payload.bin      all bytes (mod files, DLLs, setup window pictures), included with .incbin
  native_d2/setup/gen/payload_table.c  what is where: the mod files with their index entries, the strings to add to
                                       each language file, the DLLs, the pictures, the version

Decisions the Python setup (tools/vg_setup.py) makes at install time from the player's index but that never change
are made here, from the stock index: the type / name / flags of each new entry (a decl's type is the type of the
stock decls in its folder). The rest -- which catalogs already have a path, the current text files -- stays at
install time. Run by tools/vg_build.py.
"""
import json
import os
import re
import shutil
import sys

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
MOD = os.path.join(ROOT, "d2mods", "VoidGate")
NATIVE = os.path.join(ROOT, "native_d2")
GEN = os.path.join(NATIVE, "setup", "gen")
FLAG_FILE = 0x20

sys.path.insert(0, os.path.join(ROOT, "tools"))


def c_str(s):
    """A C string literal, every byte outside printable ASCII as an octal escape (safe next to any character)."""
    out = []
    for b in s.encode("utf-8") if isinstance(s, str) else s:
        c = chr(b)
        out.append("\\%03o" % b if b < 32 or b > 126 or c in '"\\?' else c)
    return '"' + "".join(out) + '"'


def stock_dir_types():
    import d2install
    return d2install.Stock().dir_type


def main(version):
    os.makedirs(GEN, exist_ok=True)
    info = json.load(open(os.path.join(MOD, "mod.json"), encoding="utf-8"))
    entries = info.get("entries", {})
    new_cats = info.get("new_catalogs", [1])
    dir_type = stock_dir_types()
    blob = bytearray()

    def add(data):
        off = len(blob)
        blob.extend(data)
        while len(blob) % 16:
            blob.append(0)
        return off, len(data)

    rows = []  # (path, off, size, copy, type, name, tail)
    files = {}
    root = os.path.join(MOD, "files")
    for dp, _, fns in os.walk(root):
        for fn in fns:
            rel = os.path.relpath(os.path.join(dp, fn), root).replace(os.sep, "/")
            if not entries.get(rel, {}).get("copy"):
                files[rel] = open(os.path.join(dp, fn), "rb").read()
    for path in sorted(set(files) | {p for p, e in entries.items() if e.get("copy")}):
        ent = entries.get(path, {})
        if ent.get("copy"):
            rows.append((path, 0, 0, 1, ent["type"], ent["name"], bytes.fromhex(ent["tail"])))
            continue
        m = re.match(r"generated/decls/([^/]+)/(.+)\.decl$", path)
        if m:
            typ, name, flag = dir_type[m.group(1)], m.group(2), 0
        elif re.match(r"generated/image/(.+)\.bimage7$", path):
            typ, name, flag = "image", path[len("generated/image/"):-len(".bimage7")] + ".png", FLAG_FILE
        else:
            typ, name, flag = "File", path, FLAG_FILE
        typ, name = ent.get("type", typ), ent.get("name", name)
        if "tail" in ent:
            tail = bytes.fromhex(ent["tail"])
        else:
            tail = bytearray(10)
            tail[7] = flag
        off, size = add(files[path])
        rows.append((path, off, size, 0, typ, name, bytes(tail)))

    langs, kvs = [], []
    langdir = os.path.join(MOD, "lang")
    for fn in sorted(os.listdir(langdir)):
        texts = json.load(open(os.path.join(langdir, fn), encoding="utf-8"))
        langs.append((fn[:-5], len(kvs), len(texts)))
        kvs += list(texts.items())

    bins = {}
    for name, path in (("dinput8", os.path.join(NATIVE, "dinput8.dll")), ("module", os.path.join(NATIVE, "voidgate.dll"))):
        bins[name] = add(open(path, "rb").read())
    ui = []
    for pct in (100, 125, 150, 175, 200):
        s = add(open(os.path.join(MOD, "art", "setup", f"side_{pct}.png"), "rb").read())
        i = add(open(os.path.join(MOD, "art", "setup", f"icon_{pct}.png"), "rb").read())
        ui.append((pct, s, i))

    open(os.path.join(GEN, "payload.bin"), "wb").write(blob)
    # version resource and icon for setup.rc
    major, minor, patch = (int(x) for x in version.split("."))
    open(os.path.join(GEN, "version.h"), "w", newline="\n").write(
        f"#define VG_VER_MAJOR {major}\n#define VG_VER_MINOR {minor}\n#define VG_VER_PATCH {patch}\n"
        f'#define VG_VER_STRING "{version}"\n')
    shutil.copy2(os.path.join(MOD, "art", "voidgate.ico"), os.path.join(GEN, "voidgate.ico"))
    L = ["// generated by tools/vg_payload.py -- do not edit", '#include "../payload.h"', "",
         f"const char VG_VERSION[] = {c_str(version)};", ""]
    L.append("const vg_file_t VG_FILES[] = {")
    for path, off, size, copy, typ, name, tail in rows:
        L.append(f"    {{{c_str(path)}, {off}u, {size}u, {copy}, {c_str(typ)}, {c_str(name)}, "
                 f"{{{', '.join('0x%02X' % b for b in tail)}}}}},")
    L.append("};")
    L.append(f"const int VG_NFILES = {len(rows)};")
    L.append(f"const int VG_NEW_CATALOGS[4] = {{{', '.join(str(int(g in new_cats)) for g in (1, 2, 3, 4))}}};")
    L.append("")
    L.append("const vg_kv_t VG_KV[] = {")
    for k, v in kvs:
        L.append(f"    {{{c_str(k)}, {c_str(v)}}},")
    L.append("};")
    L.append("const vg_lang_t VG_LANGS[] = {")
    for stem, first, n in langs:
        L.append(f"    {{{c_str(stem)}, {first}, {n}}},")
    L.append("};")
    L.append(f"const int VG_NLANGS = {len(langs)};")
    L.append("")
    L.append(f"const vg_blob_t VG_DINPUT8 = {{{bins['dinput8'][0]}u, {bins['dinput8'][1]}u}};")
    L.append(f"const vg_blob_t VG_MODULE = {{{bins['module'][0]}u, {bins['module'][1]}u}};")
    L.append("const vg_ui_t VG_UI[5] = {")
    for pct, s, i in ui:
        L.append(f"    {{{pct}, {{{s[0]}u, {s[1]}u}}, {{{i[0]}u, {i[1]}u}}}},")
    L.append("};")
    L.append("")
    L.append('__asm__(".section .rdata,\\"dr\\"\\n.balign 16\\n.global vg_payload\\nvg_payload:\\n'
             '.incbin \\"' + os.path.join(GEN, "payload.bin").replace("\\", "/") + '\\"\\n.text\\n");')
    open(os.path.join(GEN, "payload_table.c"), "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print(f"native payload: {len(rows)} mod files ({sum(r[3] for r in rows)} stock copies), {len(langs)} languages, "
          f"{len(kvs)} strings, {len(blob) // 1024} KB")


if __name__ == "__main__":
    from vg_setup import VERSION
    main(VERSION)
