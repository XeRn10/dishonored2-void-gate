"""Code signature of the game build Void Gate was made for: native_d2/vg_sig.h.

Every Dishonored2.exe address the native code uses (hex constants 0x14xxxxxxx in host.c / vg.c) that lies in code
(.text) or read-only data (.rdata: vtables, constant tables) is listed with its 16 bytes from the reference exe (GOG
1.77.9.0). At startup the host compares them all: a build with the same code (another store's exe with another
timestamp, say) runs the mod; any difference turns it off, so a different build never gets a call into the wrong
place. .data / .bss addresses are skipped (they change while the game runs).

  py tools\\make_sig.py [reference exe]      (default: D:\\Dishonored 2\\Dishonored2.exe)
"""
import os
import re
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = [os.path.join(HERE, "..", "native_d2", f) for f in ("host.c", "vg.c")]
OUT = os.path.join(HERE, "..", "native_d2", "vg_sig.h")
EXE = sys.argv[1] if len(sys.argv) > 1 else r"D:\Dishonored 2\Dishonored2.exe"
N = 16


def sections(d):
    pe = struct.unpack_from("<I", d, 0x3C)[0]
    nsec, optsz = struct.unpack_from("<H", d, pe + 6)[0], struct.unpack_from("<H", d, pe + 20)[0]
    base = struct.unpack_from("<Q", d, pe + 24 + 24)[0]
    ts = struct.unpack_from("<I", d, pe + 8)[0]
    # import address table (data directory 12): filled by the loader at startup, never the file's bytes
    iat_rva, iat_size = struct.unpack_from("<II", d, pe + 24 + 112 + 12 * 8)
    out = [("<iat>", base + iat_rva, iat_size, 0, 0)]
    for i in range(nsec):
        o = pe + 24 + optsz + 40 * i
        name = d[o:o + 8].rstrip(b"\0").decode()
        vsz, va, rsz, raw = struct.unpack_from("<IIII", d, o + 8)
        out.append((name, base + va, vsz, raw, rsz))
    return base, ts, out


def main():
    d = open(EXE, "rb").read()
    base, ts, secs = sections(d)
    iat = secs[0]
    keep = {s[0]: s for s in secs if s[0] in (".text", ".rdata")}
    addrs = set()
    for f in SRC:
        for m in re.finditer(r"0x(14[0-9A-Fa-f]{7})(?:ull)?\b", open(f, encoding="utf-8").read()):
            addrs.add(int(m.group(1), 16))
    rows = []
    for a in sorted(addrs):
        if iat[1] <= a < iat[1] + iat[2]:
            continue  # (an import slot)
        for name, va, vsz, raw, rsz in keep.values():
            if va <= a and a + N <= va + min(vsz, rsz):
                rows.append((a, name, d[raw + a - va:raw + a - va + N]))
                break
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// generated by tools/make_sig.py from %s (timestamp %08X): the bytes the mod expects at every\n"
                "// game address it uses in .text / .rdata -- all must match, or the mod stays off\n" %
                (os.path.basename(EXE), ts))
        f.write("#define VG_SIG_TIMESTAMP 0x%08Xu\n" % ts)
        f.write("static const struct { unsigned long long va; unsigned char b[%d]; } VG_SIG[] = {\n" % N)
        for a, name, b in rows:
            f.write("    {0x%Xull, {%s}},  // %s\n" % (a, ",".join("0x%02X" % x for x in b), name))
        f.write("};\n")
    print(f"{len(rows)} of {len(addrs)} addresses in .text/.rdata -> {os.path.relpath(OUT)}")


if __name__ == "__main__":
    main()
